// ─── 4. FETCH AND PARSE WIKIPEDIA VC LIST ───────────────────────────────────
async function fetchWikipediaVCList() {
  console.log('\n--- Fetching Wikipedia VC list ---');
  const records = [];

  try {
    const url = 'https://en.wikipedia.org/w/api.php?action=parse&page=List_of_venture_capital_firms&prop=wikitext&format=json';
    const res = await fetchWithRetry(url);
    if (!res || !res.ok) {
      console.log('  Wikipedia fetch failed, status:', res?.status);
      return records;
    }

    const json = await res.json();
    const wikitext = json?.parse?.wikitext?.['*'] || '';

    // Parse wikitext table rows - looking for patterns like: | [[Firm Name]] || Location || ...
    // Wikipedia format for this page has tables with: Name | HQ | Year | Notable investments
    const lines = wikitext.split('\n');
    let inTable = false;

    for (const line of lines) {
      // Detect table start
      if (line.includes('{|')) { inTable = true; continue; }
      if (line.includes('|}')) { inTable = false; continue; }

      if (!inTable) continue;

      // Parse table rows - each cell starts with | or ||
      if (line.startsWith('|-')) continue; // row separator

      // Try to extract firm names from wiki links [[Name]] or [[Name|Display]]
      const wikiLinks = [...line.matchAll(/\[\[([^\]|]+)(?:\|([^\]]+))?\]\]/g)];
      if (wikiLinks.length === 0) continue;

      // The first wikilink in a row is usually the firm name
      const rawName = (wikiLinks[0][2] || wikiLinks[0][1]).trim();
      if (!rawName || rawName.length < 3) continue;

      // Skip headers and non-firm entries
      if (/^(name|firm|company|venture|category|list|see also)/i.test(rawName)) continue;
      if (/\d{4}/.test(rawName) && rawName.length < 6) continue;  // skip years

      // Try to extract location from the same line
      let location = null;
      const locMatch = line.match(/(?:San Francisco|New York|Boston|Chicago|Los Angeles|Seattle|Austin|Palo Alto|Menlo Park|Mountain View|Washington|Silicon Valley|London|Beijing|Shanghai|Singapore|Mumbai|Berlin|Paris|Tel Aviv|Toronto)/i);
      if (locMatch) location = locMatch[0];

      // Try to get state from context
      const stateMatch = line.match(/,?\s*(California|CA|New York|NY|Massachusetts|MA|Illinois|IL|Texas|TX|Washington|WA|Virginia|VA|Colorado|CO|Georgia|GA|Connecticut|CT|Pennsylvania|PA|Maryland|MD|Florida|FL)/i);
      if (stateMatch && location) {
        location = `${location}, ${stateMatch[1]}`;
      }

      records.push({
        name: rawName,
        organization: rawName,
        description: `Venture capital firm listed on Wikipedia's List of Venture Capital Firms.`,
        location: location || null,
        opportunity_type: 'vc',
        stage: ['seed', 'series-a', 'series-b'],
        sectors: ['Technology'],
        confidence_score: 70,
        raw_input: JSON.stringify({ source_line: line.substring(0, 300) }),
        field_sources: { name: 'wikipedia_vc_list', location: 'wikipedia_vc_list' },
      });
    }

    console.log(`  Parsed ${records.length} firms from Wikipedia VC list`);
  } catch (err) {
    console.error('  Wikipedia scraping error:', err.message);
  }

  return records;
}

// ─── 5. TRY NVCA MEMBER LIST ────────────────────────────────────────────────
async function fetchNVCAMembers() {
  console.log('\n--- Attempting NVCA member directory ---');
  const records = [];

  try {
    // NVCA member directory may require authentication; try the public-facing page
    const url = 'https://nvca.org/nvca-members/';
    const res = await fetchWithRetry(url);
    if (!res || !res.ok) {
      console.log('  NVCA fetch failed, status:', res?.status);
      return records;
    }

    const html = await res.text();

    // Try to extract member names from the HTML
    // Look for patterns like <h3>Firm Name</h3> or list items with firm names
    const nameMatches = [...html.matchAll(/<(?:h[2-4]|strong|a[^>]*class="[^"]*member[^"]*"[^>]*)>([^<]{3,80})<\//gi)];
    for (const m of nameMatches) {
      const name = m[1].trim().replace(/&amp;/g, '&').replace(/&#\d+;/g, '');
      if (name.length < 3 || name.length > 80) continue;
      if (/^(menu|search|home|about|contact|login|back|next|prev)/i.test(name)) continue;

      records.push({
        name,
        organization: name,
        description: 'NVCA member firm - National Venture Capital Association.',
        opportunity_type: 'vc',
        stage: ['seed', 'series-a', 'series-b', 'growth'],
        sectors: ['Technology'],
        confidence_score: 70,
        field_sources: { name: 'nvca_directory' },
      });
    }

    console.log(`  Parsed ${records.length} firms from NVCA`);
  } catch (err) {
    console.error('  NVCA scraping error:', err.message);
  }

  return records;
}

